一つは、情報の流れる場そのものを運営する側である。多くの人が集い、情報をやりとりする場を用意し、そこでどの情報を優先的に示すかを決める仕組みを設計している以上、その設計がもたらす影響について、なんらかの責任を負うべきだ、という考え方がある。人の注目を引きつけ、より長くとどまらせるように場を設計すれば、感情を刺激する情報がおのずと広がりやすくなる。その仕組みを作った側は、意図の有無にかかわらず、生じた結果に無関係ではいられない。しかし、公に選ばれたわけでもない運営の側が、人々の見聞きするものをどこまで左右してよいのか、という問いもまた残る。害を防ぐための判断が、いつのまにか、一部の価値観による選別へと転じる危険がある。

