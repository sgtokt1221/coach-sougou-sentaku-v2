そしてもう一つは、社会全体、すなわち公の側である。情報の世界のあり方を、個人と運営の側だけに委ねるのではなく、社会として一定の枠組みを定め、その枠組みを開かれた議論のなかで見直していく。何を守り、何に対処するかの境界を、一部の者の判断に委ねるのではなく、社会全体で少しずつ探り、その決め方そのものを透明にしておく。ここで大切なのは、決定の過程が開かれ、説明されていることである。どのような理由で、何が制限され、何が守られるのかが隠されていれば、人々の不信だけが募る。反対に、その理由が語られ、異議を申し立てる道が開かれていれば、結果に納得できなくとも、少なくとも手続きの公正さは保たれる。

