もう一つの鍵は、負けた側の声が、決定の後も封じられないことである。民主主義の強みは、一度の決定がすべてを終わらせないところにある。いま少数であっても、語り続け、支持を広げれば、やがて多数になりうる。決定はつねに、後から問い直され、改められる可能性に開かれている。この、負けても次がある、という見通しがあるからこそ、人々は今回の敗北を受け入れることができる。もし、一度の決定がすべてを固定し、少数の側に二度と巡ってこないなら、人々が決定に従う理由は失われてしまう。民主主義への信頼は、勝った者の満足よりも、負けた者がなお希望をもてるかどうかに、深く支えられているのである。

