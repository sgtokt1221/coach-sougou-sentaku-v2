一つの論点は、決定の透明性である。どのような基準で優先順位が決められているのかが、あらかじめ社会に開かれ、説明されていることは、配分が受け入れられるための大切な条件だといえる。基準が隠されていれば、選ばれなかった人は、自分がなぜ後回しにされたのかを知ることができず、不信と怒りだけが残る。反対に、基準が明示され、その理由が語られていれば、結果に納得できなくとも、少なくとも手続きの公正さは保たれる。

もう一つの論点は、決定の重荷を、現場の個人だけに背負わせないことである。目の前の患者のうちだれを優先するかという判断を、その場の医療者一人の良心だけに委ねれば、その負担はあまりに重い。だからこそ、あらかじめ社会や制度の側で基準を用意し、現場の判断を支える仕組みが求められる。個々の医療者が孤立して過酷な選択を強いられるのではなく、その選択を社会全体で分かちあう姿勢が必要なのである。

さらに、決定の場にだれの声が反映されるべきか、という論点もある。医療の専門家だけでなく、患者やその家族、そして広く社会の人々の考えが、基準づくりに関わることには意味がある。配分の基準は、単なる医学の問題ではなく、社会がどのような価値を大切にするのかという選択だからである。だれの命を、どのような理由で優先するのかという問いは、結局のところ、わたしたちがどのような社会に生きたいのかという問いと地続きなのである。

