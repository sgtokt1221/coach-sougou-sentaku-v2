民主主義をめぐる近年の議論で、しばしば話題になるのが、人々の強い不満や願いが、既存の政治のあり方への異議として一気に噴き出す現象である。政治が一部の者に握られ、ふつうの人々の声が届いていない、という感覚が広がるとき、その不満を束ね、人々の側に立つことを掲げる動きが力をもつことがある。こうした動きを、どう受け止めればよいのだろうか。

