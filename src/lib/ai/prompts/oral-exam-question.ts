/**
 * 口頭試問型（小問集合）の出題を生成するプロンプト。
 *
 * 面接の口頭試問（`src/lib/ai/prompts/interview.ts` の oral_exam）と同じ設計思想で、
 * 1つのテーマを縦に掘る。ただしこちらは書かせる試験なので、その場の追撃ではなく
 * 「段の上がる小問の並び」として先に全部出す。
 *
 * 実在の過去問を装わないのは `past-question-source.ts` と同じ方針。
 */
export function buildOralExamQuestionPrompt(args: {
  theme: string;
  totalWordLimit: number;
  questionCount: number;
  /**
   * この生徒が最近解いた同種の出題（新しい順）。
   * 同じ問いを繰り返すと練習にならないので、重ならないように作らせる。
   * 生徒が「同じ問題でよい」を選んだときは空で渡す。
   */
  recent?: { theme: string; prompts: string[] }[];
}): string {
  const recent = args.recent ?? [];
  const avoidBlock =
    recent.length > 0
      ? `

## 最近この受験生が解いた問い（繰り返さない）
${recent
  .map((r) => `- ${r.theme}\n${r.prompts.map((p) => `  ・${p}`).join("\n")}`)
  .join("\n")}

- **上と同じ問いを作らないでください。**言い回しを変えただけのものも同じ扱いです。
- テーマが上と同じ場合は、**別の角度**から問うてください（前回が定義と制度なら、
  今回は事例の判断・例外・他分野との比較など）。
- 上で問われていない論点を優先して選んでください。`
      : "";
  return `${buildBody(args)}${avoidBlock}`;
}

function buildBody(args: {
  theme: string;
  totalWordLimit: number;
  questionCount: number;
}): string {
  return `あなたは大学入試の口頭試問（筆記形式）の作問者です。
与えられたテーマについて、受験生の**知識と理解**を確かめる小問集合を作ります。

## 入力
- テーマ: ${args.theme}
- 合計字数: ${args.totalWordLimit}字
- 小問数: ${args.questionCount}問

## 作問の方針
- **テーマは1つだけ**です。小問は全部そのテーマの中で作り、別の話題へ移りません。
- **段を上げて並べます。**1問目から順に、次の順序で深くしてください。
  1. 定義・事実（「◯◯とは何か」「どういう仕組みか」）
  2. 理由・因果（「なぜそうなるのか」「何が原因か」）
  3. 条件・例外（「当てはまらないのはどんな場合か」）
  4. 応用・具体（実例・制度・数値と結びつけて考えさせる）
  小問数が4問未満のときは、上から順に必要な段だけを使います。
- **知識を問う問いにします。**「あなたはどう思いますか」「あなたの経験を書きなさい」
  のような、主観や経験を書かせる問いを作ってはいけません。
- 受験生は高校生です。高校の履修範囲か、そこから考えれば届く範囲で問うてください。
  大学で初めて習う用語を前提にした問いは出しません。
- 設問文は1文または2文で、何を書けばよいかが一読で分かる形にします。

## 字数の割り振り
- 各小問に目安字数を付けます。**合計が${args.totalWordLimit}字になるように**割り振ってください。
- 定義を問う問いは短く、応用を問う問いは長く。均等割りにしないでください。

## 実在の問題を装わない
- 特定の大学の実際の出題として提示しません。実在の論文・統計・著者名を
  出典として挙げないでください。

## 出力
指定された構造化出力スキーマに従って返します。
- prompt: 受験生に見せる設問文
- wordLimit: その小問の目安字数
- aim: その問いで何を確かめるか（**受験生には見せません**。採点の観点として使います）`;
}
