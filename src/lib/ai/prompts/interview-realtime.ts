/**
 * interviewTendency を「人間可読な短いラベル列」に整形。
 * AI が末尾のキーワード列を読み上げないよう、JSON.stringify は使わない。
 */
function formatInterviewTendency(t: InterviewTendency | undefined): string {
  if (!t) return "";
  if (typeof t === "string") return t;
  // オブジェクトの場合は「キー: 値」を改行で並べた簡潔な形式に
  const lines: string[] = [];
  for (const [k, v] of Object.entries(t)) {
    if (v === null || v === undefined) continue;
    const display = Array.isArray(v) ? v.join("、") : String(v);
    if (display.trim()) lines.push(`- ${k}: ${display}`);
  }
  return lines.join("\n");
}

/**
 * GD speaker 用の session.instructions を生成する。
 * **重要**: 長すぎる instructions は OpenAI Realtime が末尾を発話に漏らすため、
 * 背景情報 (大学名・AP・面接傾向・弱点) は instructions に含めない。
 * それらは `buildRealtimeGdSpeakerContextMessage` で別経路 (conversation.item.create)
 * から hidden な user role メッセージとして注入する。
 */
export function buildRealtimeGdSpeakerInstructions(
  speaker: GdSpeakerKey,
  theme?: string,
): string {
  let characterPrompt = GD_CHARACTER_PROMPTS[speaker];

  // moderator の開幕台詞にテーマを差し込む。theme 未指定時は placeholder を空に。
  if (speaker === "moderator") {
    const announcement =
      theme && theme.trim()
        ? `本日のテーマは『${theme.trim()}』です。それでは、どなたからでも結構ですので、ご意見をお願いします。`
        : "";
    characterPrompt = characterPrompt.replace("{{THEME_ANNOUNCEMENT}}", announcement);
  }

  return `${characterPrompt}

## 絶対ルール (厳守)
- 日本語で話す
- 自分のキャラクターだけを演じる。他のキャラクターを代弁しない
- 発言は短く (1-3 文)
- 相槌だけの発言は禁止。必ず立場や理由を添える
- **ユーザー (受験生のひとり) には固有名がない**。指名する必要があるときは「もうひとりの受験生の方」のように非固有で言及する。「Dさん」「Aさん」など仮名を勝手に作らない
- 他の受験生は displayName (健太・美咲・翔太) で呼ぶ。「受験生A」「受験生B」「受験生C」「受験生D」のような汎用呼称は使わない
- 集団討論である以上、他の参加者の名前を呼んで議論する
- 背景情報メッセージ (大学名・AP・面接傾向・弱点メモ等) を**そのまま読み上げない**。自分の言葉で噛み砕いて議論に活かす

## テーマ準拠 (最重要)
- **司会が opening で発表したテーマを議論全体の軸にする**。テーマから逸脱した話題に流れない
- 自分のキャラクター設定 (積極的・データ重視・独創的) はあくまでテーマに対する切り口であり、キャラクター自体を論じるのは NG
- テーマが「持続可能な社会」なら、健太でも美咲でも翔太でも、議論内容は持続可能性に関わるものに限る

## 発言の捏造禁止 (最重要)
- **過去に実際に broadcast された他者の発言にだけ言及する**。履歴に無い発言を捏造して引用してはならない
- 「〇〇さんが言った通り」「先ほどの話にあったように」のような引用は、**実際にその発言が履歴に存在する場合のみ**許される
- 議論開幕直後など、まだ誰の発言も無い状態では、他者発言の引用を一切せず、テーマに対する自分の立場から議論を始めること
- 履歴の「[他の参加者の発言 - 〇〇]」というラベルは識別用のメタ情報。**自分の発話では「〇〇さんは」「司会の方は」のように自然に言い換え、ラベル文字列をそのまま読み上げない**

## 傾聴の姿勢 (重要)
- **反論するときでも必ず「〇〇さんの意見は分かります」など一度受け止めてから自分の立場を述べる**
- 「いえ」「違います」「でも」のような否定語から発言を始めるのは NG
- 相手の発言内容を自分の言葉で要約してから補強・反論する
- ユーザーの発言に対しても必ず同じ姿勢で臨む。相手を否定から入らないこと
`;
}

/**
 * GD セッション接続後、最初の triggerResponse 前に
 * `conversation.item.create` (role: "user") で hidden 注入する**背景情報メッセージ**。
 *
 * これにより instructions 本文を短く保ち、長文 AP・弱点リスト・面接傾向が
 * AI の発話末尾に漏れる事故を防ぐ。AI は conversation 履歴の文脈として
 * 内容を参照できるが、user message の体裁なので「自分の台詞」として
 * 直接読み上げる確率は大きく下がる。
 */
export function buildRealtimeGdSpeakerContextMessage(
  universityName: string,
  facultyName: string,
  admissionPolicy: string,
  weaknessList: string,
  interviewTendency?: InterviewTendency,
  theme?: string,
): string {
  const tendencyText = formatInterviewTendency(interviewTendency);
  const lines: string[] = [
    "<my-internal-notes>",
    "※ これは「あなた自身の内心メモ」です。あなたが既に把握している背景情報を再確認するだけのもので、",
    "  この内容を**そのまま音声で読み上げてはいけません**。",
    "※ 自分の言葉で噛み砕いて、議論の中で必要な部分だけを反映してください。",
    "",
    `[討論の文脈] ${universityName} ${facultyName} の入学試験における集団討論`,
  ];
  if (theme && theme.trim()) {
    lines.push(
      "",
      "[討論テーマ] (司会が開幕で発表するテーマ。議論はこのテーマに沿って行う)",
      theme.trim(),
    );
  }
  lines.push(
    "",
    "[アドミッションポリシー]",
    admissionPolicy,
  );
  if (tendencyText) {
    lines.push("", "[この学部の面接傾向]", tendencyText);
  }
  if (weaknessList && weaknessList.trim()) {
    lines.push("", "[今回の受験生の弱点メモ (内心で意識、発言では言及しない)]", weaknessList);
  }
  lines.push("", "</my-internal-notes>");
  return lines.join("\n");
}

function buildSelfAnalysisSection(sa: SelfAnalysisContext): string {
  const parts: string[] = [
    "## 受験生の自己分析結果 (面接で深掘りすべき素材)",
    "以下は受験生が事前の自己分析で明らかにした内容です。この情報を踏まえて、受験生の人物像をより深く理解した上で質問を組み立ててください。表面的な確認ではなく、自己分析の内容と AP の整合性を鋭く掘り下げてください。",
  ];
  if (sa.values?.length) {
    parts.push(`- 大切にしている価値観: ${sa.values.join("、")}`);
  }
  if (sa.strengths?.length) {
    parts.push(`- 強み: ${sa.strengths.join("、")}`);
  }
  if (sa.vision) {
    parts.push(`- 将来の理想像: ${sa.vision}`);
  }
  if (sa.selfStatement) {
    parts.push(`- 自己紹介文: ${sa.selfStatement}`);
  }
  parts.push("");
  return parts.join("\n");
}
