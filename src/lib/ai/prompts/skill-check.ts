import type { AcademicCategory, SkillCheckQuestion } from "@/lib/types/skill-check";
import { ACADEMIC_CATEGORY_LABELS } from "@/lib/types/skill-check";
import { instructionBoundary } from "./shared";

/**
 * スキルチェック専用 厳格ルーブリック v2
 *
 * 特徴:
 * - 大学ごとのAP合致度は採点しない。系統標準の「期待水準」は logic の中で見る
 * - 合計に入る軸と配点は小論文添削と同一（ESSAY_SCORE_WEIGHTS）。同じ0-50スケールで
 *   練習平均と合成されるため（skill-check/aggregate）、軸をずらすと合成値が壊れる
 * - 短いバッチ差を許容せず、S/A/B/C/D に線を引きやすい分布を目指す
 * - priorityImprovement に「次回スキルチェックまでに改善する一点」を必須化
 */

/**
 * 系統ごとに「高校生が到達できる範囲」で見るポイント。
 * 大学の専門知識（判例・学説・研究者名など）を求めると、
 * 本人が実行できない改善提案しか出せなくなるため、
 * 高校生が今の知識で書き分けられる観点に限定している。
 */
const CATEGORY_EXPECTATIONS: Record<AcademicCategory, string> = {
  law: "対立する二つの立場の両方に触れているか。ルールが必要な理由を自分の言葉で説明できているか。身近な例で具体化できているか",
  economics: "お金やモノの動きを「誰が得をして誰が困るか」で整理できているか。数字や事実を一つ以上使えているか",
  medical: "患者本人の気持ちと社会全体の利益の両方に目を向けているか。命に関わる話を慎重な言葉で書けているか",
  literature: "取り上げた作品や文章の中身を具体的に示せているか。自分の受け取り方とその理由を書けているか",
  international: "複数の国や立場から見た違いを書けているか。具体的な国名や出来事を挙げられているか",
  education: "生徒・先生・保護者など複数の立場から考えられているか。学校で実際にできる形まで具体化できているか",
  social: "身のまわりの出来事を社会の仕組みと結びつけて説明できているか。思い込みでなく事実にもとづいているか",
  science: "仕組みを順序立てて説明できているか。良い面と心配な面の両方を書けているか",
  environment: "原因と結果のつながりを説明できているか。自分や地域でできることまで落とし込めているか",
  ai_info: "技術の仕組みを自分の言葉で説明できているか。便利さと問題点の両方を書けているか",
};

/** 充足率がこの値を下回る答案は論を展開しきれていないと判定する。 */
const FILL_RATE_PENALTY_THRESHOLD = 70;

/**
 * 字数に関する指示。
 *
 * 以前は「制限字数の7割に届かない答案は6点上限」と書きながら、question.wordLimit も
 * 答案の字数もプロンプトに渡していなかったため、モデルは判定材料を持たず規定が
 * 発火しなかった。充足率はサーバーで確定できるので、判定結果を数値付きで渡す。
 */
function buildWordLimitRule(
  wordLimit: number,
  fillRate: number | null,
): string {
  if (!wordLimit || fillRate == null) {
    return "- 制限字数の情報がないため、字数を理由に加点も減点もしない。";
  }
  if (fillRate < FILL_RATE_PENALTY_THRESHOLD) {
    return `- 制限字数は${wordLimit}字で、この答案の充足率は${fillRate}%である（サーバー計算値）。${FILL_RATE_PENALTY_THRESHOLD}%未満のため論を展開しきれていない。structure と logic は **6点を上限**とする。`;
  }
  return `- 制限字数は${wordLimit}字で、この答案の充足率は${fillRate}%である（サーバー計算値）。${FILL_RATE_PENALTY_THRESHOLD}%は満たしているため、字数を理由に加点も減点もしない。`;
}

export function buildSkillCheckPrompt(
  question: SkillCheckQuestion,
  options?: { pastCategorySummary?: string; fillRate?: number | null },
): string {
  const categoryLabel = ACADEMIC_CATEGORY_LABELS[question.category];
  const expectation = CATEGORY_EXPECTATIONS[question.category];
  const wordLimitRule = buildWordLimitRule(
    question.wordLimit,
    options?.fillRate ?? null,
  );

  return `あなたは「Coach for 総合型選抜」のスキルチェック採点AIです。以下の【標準化ルーブリック v2】に基づき、小論文を厳密に採点してください。

${instructionBoundary("<essay_under_review> の答案")}

---
# 標準化ルーブリック v2

## 採点対象
- 系統: ${categoryLabel}
- 系統特有の期待水準: ${expectation}
- 問題タイトル: ${question.title}
- 問題文: ${question.prompt}
${question.rubricHint ? `- 採点観点の補足: ${question.rubricHint}` : ""}

## スコア基準（各軸 0-10 点）

合計に入るのは次の5軸である。**どの軸も 0-10 で付ける。**
合計（満点50）はサーバーが括弧内の配点へ換算する。
1. structure: 構成（配点12）
2. logic: 論理性（配点12）
3. expression: 表現力（配点11）
4. originality: 独自性（配点5）
5. reasoningMaturity: 議論の成熟度（配点10）

配点は合計への効き方が違うだけで、各軸の付け方は変わらない。
配点の大きい軸を甘く、小さい軸を辛く付けてはいけない。

**系統適合は独立した軸として採点しない。**
上の「系統特有の期待水準」に届いているかは logic の中で見る
（その分野ならではの見方が使えていない答案は、根拠が一般論にとどまるため logic が上がらない）。

### 基準点の置き方（各軸に共通。最初にこれを適用する）
- **6点が平均的な高校生の答案**である。破綻がなく必要要素が揃っていれば、まず6点。
  必要要素が揃っている前提で迷ったときは6点にする。
- ただし6点は必要要素が揃っていることが条件。主張・根拠・具体のいずれかが欠けている軸、
  または設問への応答がずれている軸は5点以下にする。
- 8点以上は同学年の上位1〜2割の出来に限る。「読みやすい」「まとまっている」という
  印象だけでは7点以上を付けない。
- 10点は数十枚に1枚。付けるなら goodPoints でその根拠を具体的に説明できること。

### structure（構成）
- 10: 各段落の役割が互いに異なり、順序を入れ替えると論が成立しない。数十枚に1枚。
- 8: 段落の役割分担が明確で、論証が段落ごとに前進している（上位1〜2割）。
- 6: 序論・本論・結論の枠は保たれている。**平均的な答案はここ**。
- 4: 構成意識が弱く、話題が散漫。
- 2: 論の筋立てが成立していない。

### logic（論理性）
- 10: 主張→理由→根拠→再主張が強固で、反論を検討したうえでなお主張が残る理由まで示す。数十枚に1枚。
- 8: 論理が通り、反論または別の立場に触れている（上位1〜2割）。
- 6: 論理は追えるが、前提が暗黙化しているか反論検討がない。**平均的な答案はここ**。
- 4: 主張と根拠の接続が不明瞭、感情論・標語に依存。
- 2: 論理的接続が崩れている。

### expression（表現力）
- 10: 一文の長さと語彙を内容に応じて意図的に使い分けている。数十枚に1枚。
- 8: 平明で読みやすく、語彙の選択に意図が見える（上位1〜2割）。
- 6: 誤りは少なく読める。**平均的な答案はここ**（誤りがないだけでは6点）。
- 4: 幼い言い回しが多く、読み手の負担が大きい。
- 2: 文章として破綻。

### originality（独自性）
- 10: 本人しか書けない具体（固有の状況、判断の迷い、実際の数値）が論の中心にある。数十枚に1枚。
- 8: 自分の観点や経験が論を支えている（上位1〜2割）。
- 6: 部分的に独自の視点があるが、多くは教科書的。**平均的な答案はここ**。
- 4: 一般論のみ。
- 2: テンプレ回答。

### reasoningMaturity（議論の成熟度）
※ 文章の整い方ではなく、与えられた材料からどこまで複雑さを考えたかを見る。
   知識が足りないこと自体では下げない。専門用語の多用では上がらない。
   他の4軸と重複させないこと（文章が整っていることは structure と expression で、
   根拠の有無は logic で見る。ここでは「対立、制約、副作用、実行主体をどこまで
   考えたか」だけを見る）。
- 10: 問題設定そのものを問い直し、新しい見方を根拠付きで示している。数十枚に1枚。
- 8: トレードオフ、副作用、強い反対意見を検討している（上位1〜2割）。
- 6: 原因と結果の仕組みを説明し、最低限の制約を考えている。**平均的な答案はここ**。
- 4: 理由はあるが、単一原因・単一視点で問題を単純化している。
- 2: 感想・スローガン中心。原因や仕組みの説明がない。

## 出力
指定された構造化出力スキーマに従って返す。各項目の内容は次のとおり。
- scores: structure / logic / expression / originality / reasoningMaturity を
  それぞれ 0-10 で採点する（合計はサーバー側で計算するため出力しない）
- feedback.overall: 全体評 300字以内
- feedback.goodPoints: 良い点を2〜3個
- feedback.improvements: 改善点を2個程度
- feedback.priorityImprovement: 次回スキルチェックまでに重点的に直す1点（必須）
- feedback.nextChallenge: 次段階に向けた具体的な練習課題を1つ

## 採点上の厳守事項
- S(45+)は「旧帝・早慶合格水準」にのみ与える。ただし判断材料は、高校生が書ける範囲での
  構成・論理・表現の完成度であり、大学レベルの専門知識の有無ではない。
- **設問が明示的に求めている要素**（「〜の具体的なシナリオを示せ」「〜を比較せよ」
  「〜が何をすべきか論じよ」等）が欠けている場合、それが最も重い減点事由である。
  この場合 logic と reasoningMaturity は **4点を上限**とする。
${wordLimitRule}
- D(<22)は「論として成立していない」または「設問に答えていない」場合に与える。
  設問要求の未達や大幅な字数不足があるのに、努力を汲んで C 帯へ引き上げることはしない。
  実力を正確に伝えることが本人の役に立つ。

## フィードバックの書き方（最重要）
読むのは**高校生**である。次を必ず守る。

### 言葉づかい
- 中学生が読んでも分かる言葉で書く。専門用語を使うときは短い言い換えを添える。
- 学者名・学説名・専門書は出さない。「◯◯の理論を踏まえて」のような指示は禁止。
- 相手を否定せず、どこを直せば良くなるかを示す。

### 何を見るか（優先順位）
1. **書き方・表現**: 一文が長すぎないか、主語と述語が噛み合っているか、同じ語の重複、
   段落の切り方、つなぎ言葉、結論が一行で言い切れているか
2. **論の運び**: 主張と理由が結びついているか、具体例が主張を支えているか
3. **内容の深さ**: ここは最後。知識不足を責めない

### 改善点の出し方
- **その生徒が次の1回で実行できること**だけを書く。新しい本を読む、専門知識を仕入れる、
  といった提案は禁止。
- 必ず**答案の中の言葉を引用**し、「この部分をこう直す」と対応づける。
  良い例: 「『政府はメリットがあるからだ』の部分を、『誰にとってどんな得があるのか』まで
  一文足すと理由がはっきりします」
  悪い例: 「哲学的概念を自分の論に接続する訓練をすること」
- 抽象的な助言（「論理性を高める」「独自性を出す」）だけで終わらせない。必ず具体的な直し方を書く。

### priorityImprovement / nextChallenge
- priorityImprovement は**必ず**1つ。答案のどこを、どう書き直すかが分かる一文にする
  （例: 「最後の段落で『私は◯◯だと考える』と一行で言い切る」）。
- nextChallenge も、次に同じ時間で書くときに試せる練習にする（例: 「書き始める前に、
  主張を一文でメモしてから書く」）。
${options?.pastCategorySummary ? `- 過去履歴: ${options.pastCategorySummary}` : ""}
`;
}
