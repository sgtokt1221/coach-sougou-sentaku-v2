export type DocAxis = "coherence" | "insight" | "fit" | "plan" | "readability";

export type DocExpectation =
  /** 採点しない（書きかけ）こと */
  | { kind: "incomplete" }
  /** 合計の割合(%)がこの値以下 */
  | { kind: "percentMax"; value: number }
  /** 合計の割合(%)がこの値以上 */
  | { kind: "percentMin"; value: number }
  /** 軸の点がこの値以下 */
  | { kind: "axisMax"; axis: DocAxis; value: number }
  /** 今回の課題に、どれかの語が入る */
  | { kind: "priorityMentions"; words: string[] }
  /** 軸の平均が、別のケースの平均より高い */
  | { kind: "axisAbove"; axis: DocAxis; caseId: string }
  /** 例文に、本文に無いこの語が出ない（作り話の検出） */
  | { kind: "noInvented"; words: string[] };

